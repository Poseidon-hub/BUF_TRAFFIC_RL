@dataclass
class DiplomaRun:
    mode: str
    train_episodes: int
    train_episode_seconds: int
    eval_seconds: int
    vehicle_count: int
    pedestrian_count: int
    controlled_tls: int | None
    device: str = "auto"
    seed: int = 42


def default_run(mode: str) -> DiplomaRun:
    mode = normalize_mode(mode)
    if mode == "fast":
        return DiplomaRun("fast", 1, 10, 60, 80, 40, 2, "cpu", 42)
    if mode == "validate_fast":
        return DiplomaRun("validate_fast", 1, 10, 60, 80, 40, 2, "cpu", 42)
    if mode == "long":
        return DiplomaRun("long", 40, 600, 1800, 1000, 150, None, "auto", 42)
    if mode == "manual":
        base = default_run("normal")
        base.mode = "manual"
        return base
    return DiplomaRun("normal", 10, 300, 900, 300, 50, 50, "auto", 42)


def normalize_mode(value: str) -> str:
    value = str(value or "normal").strip().lower()
    return {
        "1": "fast",
        "fast": "fast",
        "быстрый": "fast",
        "2": "normal",
        "normal": "normal",
        "нормальный": "normal",
        "3": "long",
        "long": "long",
        "долгий": "long",
        "4": "manual",
        "manual": "manual",
        "ручной": "manual",
        "validate_fast": "validate_fast",
    }.get(value, value)


def run(project_root: Path) -> int:
    project_root = Path(project_root).resolve()
    _configure_console()
    setup = resolve_setup()
    if setup is None:
        return 1

    ok, details = check_sumo_installation()
    if not ok:
        print(details or "SUMO/TraCI недоступен.")
        return 1
    ok, details = check_python_dependencies()
    if not ok:
        print(f"Не хватает Python-зависимостей: {details}")
        return 1

    cfg = make_config(project_root)
    apply_setup(cfg, setup)

    started = time.perf_counter()
    safe_mkdir(cfg.logs_dir)
    safe_mkdir(cfg.checkpoints_dir)
    safe_mkdir(cfg.scenario_dir)
    set_seed(setup.seed)

    scenario, selected_tls, pedestrian_meta = prepare_scenario(cfg, setup)
    print_summary(setup, scenario, selected_tls, pedestrian_meta)

    print()
    print("Training")
    print("--------")
    train_result = train(cfg)

    original_seconds = int(cfg.episode_seconds)
    cfg.episode_seconds = int(setup.eval_seconds)
    cfg.eval_episodes = 1
    try:
        print()
        print("Evaluation")
        print("----------")
        rl_metrics = evaluate(cfg, mode="rl", episodes=1)
        print("RL: done")
        fixed_metrics = evaluate(cfg, mode="fixed_native", episodes=1)
        print("fixed-time: done")
    finally:
        cfg.episode_seconds = original_seconds

    comparison = build_comparison(rl_metrics, fixed_metrics)
    save_outputs(cfg, setup, selected_tls, pedestrian_meta, train_result, rl_metrics, fixed_metrics, comparison)
    print_comparison(comparison)
    print_action_diagnostics(rl_metrics, fixed_metrics)
    print_runtime(started, train_result)
    return validate_result(rl_metrics, fixed_metrics, comparison, pedestrian_meta)


def resolve_setup() -> DiplomaRun | None:
    non_interactive = os.environ.get("BFU_NON_INTERACTIVE", "").strip().lower() in {"1", "true", "yes", "on"}
    if non_interactive:
        setup = default_run(os.environ.get("BFU_RUN_MODE", "normal"))
        apply_env_overrides(setup)
        return setup

    while True:
        print("1) Быстрый")
        print("2) Нормальный")
        print("3) Долгий")
        print("4) Ручной")
        try:
            choice = input("Выберите режим: ").strip() or "2"
        except (EOFError, KeyboardInterrupt):
            print()
            print("Запуск остановлен пользователем.")
            return None
        mode = normalize_mode(choice)
        if mode in {"fast", "normal", "long", "manual"}:
            break
        print("Некорректный режим. Введите 1, 2, 3 или 4.")
    setup = default_run(mode)
    if mode == "manual":
        setup = prompt_manual(setup)
    return setup


def prompt_manual(setup: DiplomaRun) -> DiplomaRun:
    return DiplomaRun(
        mode="manual",
        train_episodes=prompt_int("Количество эпизодов обучения [1 - 100]", setup.train_episodes, 1, 100),
        train_episode_seconds=prompt_int("Время одного эпизода, сек. [45 - 1800]", setup.train_episode_seconds, 45, 1800),
        eval_seconds=prompt_int("Время evaluation, сек. [30 - 3600]", setup.eval_seconds, 30, 3600),
        vehicle_count=prompt_int("Количество машин [20 - 5000]", setup.vehicle_count, 20, 5000),
        pedestrian_count=prompt_int("Количество пешеходов [0 - 1000]", setup.pedestrian_count, 0, 1000),
        controlled_tls=prompt_tls("Управляемые светофоры [1 - 270, all]", setup.controlled_tls),
        device=prompt_choice("Устройство [auto/cuda/cpu]", setup.device, {"auto", "cuda", "cpu"}),
        seed=setup.seed,
    )


def prompt_int(prompt: str, default: int, min_value: int, max_value: int) -> int:
    while True:
        raw = input(f"{prompt} ({default}): ").strip()
        if not raw:
            return int(default)
        try:
            value = int(raw)
        except ValueError:
            print("Введите целое число.")
            continue
        if min_value <= value <= max_value:
            return value
        print(f"Допустимый диапазон: {min_value} - {max_value}.")


def prompt_tls(prompt: str, default: int | None) -> int | None:
    raw_default = "all" if default is None else str(default)
    while True:
        raw = input(f"{prompt} ({raw_default}): ").strip().lower()
        if not raw:
            return default
        if raw == "all":
            return None
        try:
            value = int(raw)
        except ValueError:
            print("Введите число или all.")
            continue
        if 1 <= value <= 270:
            return value
        print("Допустимый диапазон: 1 - 270.")


def prompt_choice(prompt: str, default: str, allowed: set[str]) -> str:
    while True:
        raw = input(f"{prompt} ({default}): ").strip().lower()
        if not raw:
            return default
        if raw in allowed:
            return raw
        print(f"Допустимо: {', '.join(sorted(allowed))}.")


def apply_env_overrides(setup: DiplomaRun) -> None:
    for env_name, attr in {
        "BFU_TRAIN_EPISODES": "train_episodes",
        "BFU_TRAIN_EPISODE_SECONDS": "train_episode_seconds",
        "BFU_EVAL_SECONDS": "eval_seconds",
        "BFU_VEHICLE_COUNT": "vehicle_count",
        "BFU_PEDESTRIAN_COUNT": "pedestrian_count",
        "BFU_SEED": "seed",
    }.items():
        if os.environ.get(env_name):
            setattr(setup, attr, int(os.environ[env_name]))
    if os.environ.get("BFU_CONTROLLED_TLS"):
        value = os.environ["BFU_CONTROLLED_TLS"].strip().lower()
        setup.controlled_tls = None if value == "all" else int(value)
    if os.environ.get("BFU_DEVICE"):
        setup.device = os.environ["BFU_DEVICE"].strip().lower()


