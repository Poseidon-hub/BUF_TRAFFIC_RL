def prepare_scenario(cfg, setup: DiplomaRun):
    scenario = discover_scenario(
        cfg.scenario_dir,
        begin=0,
        end=max(setup.train_episode_seconds, setup.eval_seconds),
        step_length=cfg.step_length,
        auto_generate_sumocfg=True,
        auto_generate_pedestrians_if_missing=False,
        scenario_preferred_prefix=str(getattr(cfg, "scenario_preferred_prefix", "kaliningrad")),
    )
    if not scenario.found or not scenario.net:
        raise RuntimeError("В scenario/ не найден SUMO-сценарий с net.xml.")

    selected = select_tls_with_pedestrian_signals(Path(scenario.net), setup.controlled_tls)
    if not selected:
        raise RuntimeError("Не найдено TLS, где есть и автомобильные, и пешеходные controlled links.")

    demand_path = write_vehicle_demand(
        scenario.scenario_dir,
        Path(scenario.net),
        selected,
        setup.vehicle_count,
        begin=0,
        end=setup.eval_seconds,
    )
    cfg.scenario_route_file = demand_path.name
    cfg.allow_mixed_scenario_files = True
    cfg.scenario_sumocfg_file = None
    cfg.preferred_controlled_tls_ids = [item["tls_id"] for item in selected]
    cfg.max_controlled_tls = len(cfg.preferred_controlled_tls_ids)

    pedestrian_meta = {}
    if setup.pedestrian_count > 0:
        ok, message, _ = generate_pedestrian_demand(
            scenario_dir=scenario.scenario_dir,
            net=Path(scenario.net),
            count=setup.pedestrian_count,
            begin=0,
            end=setup.eval_seconds,
            prefix="auto_ped",
            pedestrian_mode="crossing_focused",
            preferred_controlled_tls_ids=cfg.preferred_controlled_tls_ids,
        )
        if not ok:
            raise RuntimeError(f"Не удалось создать пешеходный спрос: {message}")
        meta_path = scenario.scenario_dir / "autogenerated_pedestrians.meta.json"
        if meta_path.exists():
            pedestrian_meta = json.loads(meta_path.read_text(encoding="utf-8"))

    scenario = discover_scenario(
        cfg.scenario_dir,
        begin=0,
        end=max(setup.train_episode_seconds, setup.eval_seconds),
        step_length=cfg.step_length,
        auto_generate_sumocfg=True,
        scenario_route_file=demand_path.name,
        allow_mixed_scenario_files=True,
        auto_generate_pedestrians_if_missing=setup.pedestrian_count > 0,
        pedestrian_count=setup.pedestrian_count,
        pedestrian_begin=0,
        pedestrian_end=setup.eval_seconds,
        pedestrian_prefix="auto_ped",
        pedestrian_mode="crossing_focused",
        rl_use_real_timing_program_as_base=False,
        preferred_controlled_tls_ids=cfg.preferred_controlled_tls_ids,
    )
    return scenario, selected, pedestrian_meta


def select_tls_with_pedestrian_signals(net_path: Path, limit: int | None) -> list[dict]:
    add_sumo_tools_to_path()
    import sumolib

    net = sumolib.net.readNet(str(net_path), withPrograms=True, withConnections=True, withInternal=True)
    candidates = []
    for tls in net.getTrafficLights():
        vehicle_routes = []
        pedestrian_links = 0
        for conn in tls.getConnections():
            lanes = [item for item in conn[:2] if item is not None]
            if any(lane_allows_pedestrian(lane) and not lane_allows_vehicle(lane) for lane in lanes):
                pedestrian_links += 1
            if len(lanes) < 2:
                continue
            from_lane, to_lane = lanes[0], lanes[1]
            if not lane_allows_vehicle(from_lane) or not lane_allows_vehicle(to_lane):
                continue
            route = shortest_route_edges(net, from_lane, to_lane)
            if route and route not in vehicle_routes:
                vehicle_routes.append(route)
        if vehicle_routes and pedestrian_links > 0:
            candidates.append(
                {
                    "tls_id": str(tls.getID()),
                    "vehicle_pairs": vehicle_routes,
                    "pedestrian_signal_links": pedestrian_links,
                }
            )
    candidates.sort(key=lambda item: (item["pedestrian_signal_links"], len(item["vehicle_pairs"])), reverse=True)
    if limit is None:
        return candidates
    return candidates[: max(1, int(limit))]


def lane_allows_vehicle(lane) -> bool:
    for vehicle_class in ("passenger", "private", "bus", "truck", "taxi", "delivery"):
        try:
            if lane.allows(vehicle_class):
                return True
        except Exception:
            continue
    return False


def lane_allows_pedestrian(lane) -> bool:
    try:
        return bool(lane.allows("pedestrian"))
    except Exception:
        return False


def edge_id(lane) -> str:
    try:
        return str(lane.getEdge().getID())
    except Exception:
        return ""


def shortest_route_edges(net, from_lane, to_lane) -> list[str]:
    try:
        from_edge = from_lane.getEdge()
        to_edge = to_lane.getEdge()
        from_edge_id = str(from_edge.getID())
        to_edge_id = str(to_edge.getID())
    except Exception:
        return []
    if (
        not from_edge_id
        or not to_edge_id
        or from_edge_id == to_edge_id
        or from_edge_id.startswith(":")
        or to_edge_id.startswith(":")
    ):
        return []
    try:
        path, _ = net.getShortestPath(from_edge, to_edge)
    except Exception:
        path = None
    if not path:
        return []
    route = [str(edge.getID()) for edge in path if edge.getID() and not str(edge.getID()).startswith(":")]
    if len(route) < 2:
        return []
    return route


def write_vehicle_demand(
    scenario_dir: Path,
    net_path: Path,
    selected_tls: list[dict],
    count: int,
    begin: int,
    end: int,
) -> Path:
    output = Path(scenario_dir) / AUTOGENERATED_DIAGNOSTIC_DEMAND
    trips = Path(scenario_dir) / "autogenerated_diagnostic_trips.xml"
    end = max(begin + 1, int(end))
    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        "<routes>",
    ]
    for idx in range(max(1, int(count))):
        tls = selected_tls[idx % len(selected_tls)]
        route = tls["vehicle_pairs"][idx % len(tls["vehicle_pairs"])]
        depart = begin + (end - begin) * idx / max(1, int(count) - 1)
        lines.append(
            f'    <trip id="car_{idx}" depart="{depart:.2f}" '
            f'from="{escape(route[0])}" to="{escape(route[-1])}"/>'
        )
    lines.append("</routes>")
    trips.write_text("\n".join(lines) + "\n", encoding="utf-8")
    duarouter = detect_duarouter()
    if not duarouter:
        raise RuntimeError("Не найден duarouter. Он нужен для построения валидных маршрутов машин.")
    result = subprocess.run(
        [
            duarouter,
            "-n",
            str(net_path),
            "-r",
            str(trips),
            "-o",
            str(output),
            "--ignore-errors",
            "true",
            "--no-warnings",
            "true",
        ],
        capture_output=True,
        text=True,
        timeout=120,
    )
    if result.returncode != 0 or not output.exists():
        raise RuntimeError(result.stderr.strip() or result.stdout.strip() or "duarouter failed")
    return output


def detect_duarouter() -> str | None:
    sumo_home = os.environ.get("SUMO_HOME")
    if sumo_home:
        exe = "duarouter.exe" if os.name == "nt" else "duarouter"
        candidate = Path(sumo_home) / "bin" / exe
        if candidate.exists():
            return str(candidate)
    return None


def build_comparison(rl: dict, fixed: dict) -> dict:
    add_normalized_metrics(rl)
    add_normalized_metrics(fixed)
    rl_objective = objective_payload(rl).get("objective_score", 0.0)
    fixed_objective = objective_payload(fixed).get("objective_score", 0.0)
    vehicle_metrics = [
        "avg_queue",
        "avg_waiting_time",
        "avg_time_loss",
        "normalized_time_loss_per_departed",
        "total_waiting_time",
        "total_time_loss",
        "avg_speed",
        "arrived",
        "total_reward",
    ]
    pedestrian_metrics = ["avg_waiting_time", "total_waiting_time", "waiting_count"]
    vehicle = {
        metric: {"rl": rl.get(metric), "fixed": fixed.get(metric)}
        for metric in vehicle_metrics
        if metric != "arrived" or float(rl.get("arrived", 0) or 0) > 0 or float(fixed.get("arrived", 0) or 0) > 0
    }
    vehicle["objective_score"] = {"rl": rl_objective, "fixed": fixed_objective}
    return {
        "vehicle": vehicle,
        "pedestrian": {
            metric: {
                "rl": (rl.get("pedestrian_metrics") or {}).get(metric),
                "fixed": (fixed.get("pedestrian_metrics") or {}).get(metric),
            }
            for metric in pedestrian_metrics
        },
        "debug": {
            "throughput": {"rl": rl.get("throughput"), "fixed": fixed.get("throughput")},
            "arrived": {"rl": rl.get("arrived"), "fixed": fixed.get("arrived")},
            "pedestrian_departed": {
                "rl": (rl.get("pedestrian_metrics") or {}).get("departed"),
                "fixed": (fixed.get("pedestrian_metrics") or {}).get("departed"),
            },
            "pedestrian_arrived": {
                "rl": (rl.get("pedestrian_metrics") or {}).get("arrived"),
                "fixed": (fixed.get("pedestrian_metrics") or {}).get("arrived"),
            },
            "pedestrian_running": {
                "rl": (rl.get("pedestrian_metrics") or {}).get("running"),
                "fixed": (fixed.get("pedestrian_metrics") or {}).get("running"),
            },
        },
    }


def save_outputs(cfg, setup, selected_tls, pedestrian_meta, train_result, rl, fixed, comparison) -> None:
    payload = {
        "setup": asdict(setup),
        "controlled_tls": selected_tls,
        "pedestrian_metadata": pedestrian_meta,
        "train_result": train_result,
    }
    save_json(cfg.logs_dir / "run_config_resolved.json", payload)
    save_json(cfg.logs_dir / "comparison_rl_vs_fixed_native.json", comparison)
    write_csv_row(cfg.logs_dir / "comparison_rl_vs_fixed_native.csv", flatten_comparison(comparison))


def flatten_comparison(comparison: dict) -> dict:
    row = {}
    for section, metrics in comparison.items():
        if isinstance(metrics, dict):
            for metric, values in metrics.items():
                if isinstance(values, dict):
                    for side, value in values.items():
                        row[f"{section}_{metric}_{side}"] = value
    return row


def print_summary(setup: DiplomaRun, scenario, selected_tls: list[dict], pedestrian_meta: dict) -> None:
    print()
    print(f"Selected mode: {setup.mode}")
    print(f"Training: {setup.train_episodes} x {setup.train_episode_seconds} sec")
    print(f"Evaluation: {setup.eval_seconds} sec")
    print(f"TLS controlled: {len(selected_tls)}")
    print(f"Vehicles: {setup.vehicle_count}")
    print(f"Pedestrians: {'yes' if setup.pedestrian_count > 0 else 'no'}, {setup.pedestrian_count}")
    print(f"Pedestrian signal links: {sum(item['pedestrian_signal_links'] for item in selected_tls)}")
    print(f"Device: {setup.device}")
    print()
    print("Scenario")
    print("--------")
    print(f"net: {Path(scenario.net).name if scenario.net else '-'}")
    print(f"routes: {', '.join(Path(path).name for path in scenario.route_files)}")
    if pedestrian_meta.get("warning"):
        print(f"WARNING: {pedestrian_meta['warning']}")


def print_comparison(comparison: dict) -> None:
    print_table("Сравнение таймингов модели vs fixed-time для машин", comparison["vehicle"])
    print_table("Сравнение таймингов модели vs fixed-time для пешеходов", comparison["pedestrian"])


def print_table(title: str, metrics: dict) -> None:
    print()
    print(title)
    print("-" * len(title))
    metric_width = max(34, max((len(key) for key in metrics), default=0))
    value_width = 14
    print(f"{'Метрика':<{metric_width}}  {'Модель':>{value_width}}  {'fixed-time':>{value_width}}")
    print(f"{'-' * metric_width}  {'-' * value_width}  {'-' * value_width}")
    for metric, values in metrics.items():
        print(f"{metric:<{metric_width}}  {format_value(values.get('rl')):>{value_width}}  {format_value(values.get('fixed')):>{value_width}}")


def format_value(value) -> str:
    if value is None:
        return "n/a"
    if isinstance(value, float):
        return f"{value:.4f}"
    return str(value)


def print_action_diagnostics(rl: dict, fixed: dict) -> None:
    rl_actions = rl.get("action_stats") or {}
    fixed_actions = fixed.get("baseline_stats") or fixed.get("action_stats") or {}
    print()
    print("RL action diagnostics")
    print("---------------------")
    print(f"decisions: {rl_actions.get('decision_count', 0)}")
    print(f"switches: {rl_actions.get('switch_count', 0)}")
    print(f"phase_set: {rl_actions.get('phase_set_count', 0)}")
    print(f"fixed_phase_set: {fixed_actions.get('phase_set_count', 0)}")


def print_runtime(started: float, train_result: dict) -> None:
    print()
    print("Runtime")
    print("-------")
    print(f"total_seconds: {time.perf_counter() - started:.1f}")
    print(f"optimizer_steps: {train_result.get('optimizer_steps', 0)}")


def validate_result(rl: dict, fixed: dict, comparison: dict, pedestrian_meta: dict) -> int:
    failures = []
    rl_actions = rl.get("action_stats") or {}
    fixed_actions = fixed.get("baseline_stats") or fixed.get("action_stats") or {}
    if int(rl_actions.get("decision_count", 0) or 0) <= 0:
        failures.append("RL не принимал решений.")
    if int(rl_actions.get("phase_set_count", 0) or 0) <= 0:
        failures.append("RL не вызвал traci.trafficlight.setPhase.")
    if int(fixed_actions.get("phase_set_count", 0) or 0) != 0:
        failures.append("fixed-time baseline вручную менял фазы.")
    if int(pedestrian_meta.get("pedestrian_signal_link_count", 0) or 0) <= 0:
        failures.append("Выбранные TLS не имеют pedestrian signal links.")
    if not metrics_nonzero_and_different(comparison["vehicle"]):
        failures.append("Автомобильные primary metrics нулевые или полностью одинаковые.")
    if not metrics_nonzero_and_different(comparison["pedestrian"]):
        failures.append("Пешеходные metrics нулевые или полностью одинаковые.")
    if failures:
        print()
        print("Validation warnings")
        print("-------------------")
        for item in failures:
            print(f"WARNING: {item}")
    return 1 if failures else 0


def metrics_nonzero_and_different(metrics: dict) -> bool:
    pairs = []
    for values in metrics.values():
        try:
            rl = float(values.get("rl") or 0.0)
            fixed = float(values.get("fixed") or 0.0)
        except (TypeError, ValueError):
            continue
        pairs.append((rl, fixed))
    if not pairs:
        return False
    nonzero = any(abs(rl) > 1e-9 or abs(fixed) > 1e-9 for rl, fixed in pairs)
    different = any(abs(rl - fixed) > 1e-6 for rl, fixed in pairs)
    return nonzero and different


