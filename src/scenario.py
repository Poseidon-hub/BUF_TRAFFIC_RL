def _scenario_from_sumocfg(scenario_dir: Path, sumocfg: Path, source: str) -> ScenarioFiles:
    scenario = ScenarioFiles(
        scenario_dir=scenario_dir,
        sumocfg=sumocfg,
        autogenerated=sumocfg.name.lower() == AUTOGENERATED_SUMOCFG,
        found=True,
        source=source,
    )
    try:
        tree = ET.parse(sumocfg)
        root = tree.getroot()
    except Exception as exc:
        scenario.notes.append(f"Не удалось разобрать sumocfg: {exc}")
        return scenario

    base_dir = sumocfg.parent
    net_values = _config_values(root, {"net-file"})
    route_values = _config_values(root, {"route-file", "route-files"})
    additional_values = _config_values(root, {"additional-file", "additional-files"})

    if net_values:
        scenario.net = _resolve_config_path(base_dir, net_values[0])
    scenario.route_files = [_resolve_config_path(base_dir, value) for value in route_values]
    scenario.additional_files = [_resolve_config_path(base_dir, value) for value in additional_values]
    scenario.additional_files, scenario.timing_files = _split_timing_files(scenario.additional_files)
    return scenario


def _select_net_file(
    scenario_dir: Path,
    explicit: Optional[Path],
    preferred_prefix: str = "kaliningrad",
) -> Optional[Path]:
    explicit_path = _resolve_optional_path(scenario_dir, explicit)
    if explicit_path and explicit_path.exists():
        return explicit_path

    if preferred_prefix:
        preferred = scenario_dir / f"{preferred_prefix}.net.xml"
        if preferred.exists():
            return preferred

    matches = sorted(scenario_dir.glob("*.net.xml"))
    if matches:
        return matches[0]

    fallback = scenario_dir / "net.xml"
    return fallback if fallback.exists() else None


def _select_route_files(
    scenario_dir: Path,
    explicit: Optional[Path],
    selected_net: Optional[Path] = None,
    preferred_prefix: str = "kaliningrad",
    allow_mixed_scenario_files: bool = False,
) -> List[Path]:
    explicit_path = _resolve_optional_path(scenario_dir, explicit)
    if explicit_path and explicit_path.exists():
        prefix = _route_prefix(explicit_path)
        vtypes = scenario_dir / f"{prefix}.vtypes.xml" if prefix else None
        if vtypes and vtypes.exists() and vtypes.resolve() != explicit_path.resolve():
            return [vtypes, explicit_path]
        preferred_vtypes = scenario_dir / f"{preferred_prefix}.vtypes.xml" if preferred_prefix else None
        if (
            preferred_vtypes
            and preferred_vtypes.exists()
            and preferred_vtypes.resolve() != explicit_path.resolve()
        ):
            return [preferred_vtypes, explicit_path]
        return [explicit_path]

    net_prefix = _net_prefix(selected_net) if selected_net else ""
    prefix_routes = _route_files_for_prefix(scenario_dir, net_prefix)
    if prefix_routes:
        return prefix_routes

    if (
        selected_net
        and net_prefix
        and preferred_prefix
        and net_prefix.lower() == str(preferred_prefix).lower()
        and not bool(allow_mixed_scenario_files)
    ):
        candidates = [
            path
            for path in sorted(
                list(scenario_dir.glob("*.rou.xml"))
                + list(scenario_dir.glob("*.routes.xml"))
                + list(scenario_dir.glob("*.trips.xml"))
            )
            if path.name != AUTOGENERATED_PEDESTRIANS
            and path.name != AUTOGENERATED_DIAGNOSTIC_DEMAND
        ]
        if candidates:
            raise ValueError(
                "Scenario file mismatch: selected "
                f"{Path(selected_net).name} but route file {candidates[0].name} "
                "seems to belong to another scenario."
            )
        return []

    matches = sorted(
        list(scenario_dir.glob("*.rou.xml"))
        + list(scenario_dir.glob("*.routes.xml"))
        + list(scenario_dir.glob("*.trips.xml"))
    )
    matches = [
        path
        for path in matches
        if path.name not in {AUTOGENERATED_PEDESTRIANS, AUTOGENERATED_DIAGNOSTIC_DEMAND}
    ]
    if matches:
        return _unique_paths(matches)

    fallback = scenario_dir / "rou.xml"
    if fallback.exists():
        return [fallback]

    detected = []
    for path in sorted(scenario_dir.glob("*.xml")):
        lower_name = path.name.lower()
        if lower_name.endswith((".net.xml", ".add.xml", ".poly.xml")):
            continue
        kind, _ = _classify_xml(path)
        if kind == "route":
            detected.append(path)
    return _unique_paths(detected)


def _classify_companion_xml(
    scenario_dir: Path,
    net: Path,
    route_files: Sequence[Path],
    scenario_prefix: str = "",
    allow_mixed_scenario_files: bool = True,
    include_companion_routes: bool = True,
) -> Tuple[List[Path], List[Path], List[Path], List[str]]:
    selected_routes = _unique_paths(route_files)
    route_set = {path.resolve() for path in selected_routes}
    excluded = {net.resolve(), *route_set}
    notes: List[str] = []
    additional_files: List[Path] = []
    timing_files: List[Path] = []

    for path in sorted(scenario_dir.glob("*.xml")):
        resolved = path.resolve()
        if resolved in excluded:
            continue
        if path.name.lower().endswith(".sumocfg"):
            continue
        if path.name.lower() in {
            AUTOGENERATED_SUMOCFG,
            AUTOGENERATED_NATIVE_SUMOCFG,
            AUTOGENERATED_REAL_TIMING_SUMOCFG,
            AUTOGENERATED_RL_SUMOCFG,
            AUTOGENERATED_FILTERED_TIMING,
        }:
            continue
        if path.name in {AUTOGENERATED_PEDESTRIANS, AUTOGENERATED_DIAGNOSTIC_DEMAND}:
            continue
        if path.name.lower().endswith(".net.xml"):
            continue
        if path.suffix.lower() != ".xml":
            continue

        kind, tags = _classify_xml(path)
        if kind == "route":
            if not include_companion_routes:
                continue
            if (
                scenario_prefix
                and not bool(allow_mixed_scenario_files)
                and not _route_file_belongs_to_prefix(path, scenario_prefix)
            ):
                notes.append(
                    "Scenario file mismatch avoided: selected "
                    f"{Path(net).name} but route file {path.name} seems to belong to another scenario."
                )
                continue
            if path.name.lower() == "rou.xml" and any(
                route.name.lower() != "rou.xml" for route in selected_routes
            ):
                notes.append(f"{path.name} пропущен: основной маршрут уже выбран по шаблону *.rou.xml.")
                continue
            selected_routes.append(path)
            route_set.add(resolved)
            continue
        if kind == "additional":
            additional_files.append(path)
            continue
        if kind == "timing":
            timing_files.append(path)
            continue
        if PERSON_TAGS.intersection(tags):
            selected_routes.append(path)
            route_set.add(resolved)
            continue
        if path.name.lower().endswith((".add.xml", ".poly.xml")):
            additional_files.append(path)

    selected_routes, duplicate_notes = _drop_conflicting_route_files(selected_routes)
    notes.extend(duplicate_notes)
    additional_files, timing_from_additional = _split_timing_files(additional_files)
    timing_files.extend(timing_from_additional)
    return _unique_paths(selected_routes), _unique_paths(additional_files), _unique_paths(timing_files), notes


def _classify_xml(path: Path) -> Tuple[str, Set[str]]:
    tags: Set[str] = set()
    root_name = ""
    try:
        for _, elem in ET.iterparse(path, events=("start",)):
            name = _local_name(elem.tag)
            if not root_name:
                root_name = name
            tags.add(name)
            if len(tags) > 64 and (tags.intersection(ROUTE_TAGS) or tags.intersection(ADDITIONAL_TAGS)):
                break
    except Exception:
        return "unknown", tags

    lower_name = path.name.lower()
    if TIMING_TAGS.intersection(tags):
        return "timing", tags
    if root_name == "routes" or PERSON_TAGS.intersection(tags):
        return "route", tags
    if {"vehicle", "trip", "flow"}.intersection(tags):
        return "route", tags
    if root_name == "additional" or tags.intersection(ADDITIONAL_TAGS) or lower_name.endswith((".add.xml", ".poly.xml")):
        return "additional", tags
    if tags.intersection(ROUTE_TAGS):
        return "route", tags
    return "unknown", tags


def _drop_conflicting_route_files(route_files: Sequence[Path]) -> Tuple[List[Path], List[str]]:
    selected: List[Path] = []
    seen_ids: Set[str] = set()
    notes: List[str] = []

    for path in route_files:
        ids = _route_object_ids(path)
        duplicates = seen_ids.intersection(ids)
        if duplicates:
            preview = ", ".join(sorted(list(duplicates))[:5])
            notes.append(
                f"{path.name} skipped: duplicate route object ids already exist in earlier route files ({preview})."
            )
            continue
        selected.append(path)
        seen_ids.update(ids)
    return selected, notes


def _route_object_ids(path: Path) -> Set[str]:
    ids: Set[str] = set()
    id_tags = {
        "route",
        "vehicle",
        "trip",
        "flow",
        "person",
        "personFlow",
        "vType",
        "vTypeDistribution",
        "routeDistribution",
    }
    try:
        for _, elem in ET.iterparse(path, events=("start",)):
            if _local_name(elem.tag) in id_tags:
                obj_id = elem.attrib.get("id")
                if obj_id:
                    ids.add(obj_id)
    except Exception:
        return set()
    return ids


def _split_timing_files(paths: Sequence[Path]) -> Tuple[List[Path], List[Path]]:
    ordinary: List[Path] = []
    timing: List[Path] = []
    for path in paths:
        kind, tags = _classify_xml(Path(path))
        if kind == "timing" or TIMING_TAGS.intersection(tags):
            timing.append(Path(path))
        else:
            ordinary.append(Path(path))
    return _unique_paths(ordinary), _unique_paths(timing)


def _select_real_timing_file(timing_files: Sequence[Path], preferred_name: str) -> Optional[Path]:
    if not timing_files:
        return None
    preferred = str(preferred_name).lower()
    for path in timing_files:
        if Path(path).name.lower() == preferred:
            return Path(path)
    return Path(timing_files[0])


def _config_values(root: ET.Element, tag_names: Set[str]) -> List[str]:
    values: List[str] = []
    for elem in root.iter():
        if _local_name(elem.tag) not in tag_names:
            continue
        value = elem.attrib.get("value", "")
        values.extend(_split_config_value(value))
    return values


def _split_config_value(value: str) -> List[str]:
    chunks = []
    for item in value.replace(";", ",").split(","):
        item = item.strip()
        if item:
            chunks.append(item)
    return chunks


def _resolve_config_path(base_dir: Path, value: str) -> Path:
    path = Path(value)
    if path.is_absolute():
        return path
    return (base_dir / path).resolve()


def _resolve_optional_path(base_dir: Path, value: Optional[Path]) -> Optional[Path]:
    if value is None:
        return None
    path = Path(value)
    if path.is_absolute():
        return path
    return base_dir / path


def _relative_value(path: Path, base_dir: Path) -> str:
    try:
        rel = Path(path).resolve().relative_to(base_dir.resolve())
        return rel.as_posix()
    except Exception:
        return Path(path).as_posix()


def _unique_paths(paths: Iterable[Path]) -> List[Path]:
    result: List[Path] = []
    seen = set()
    for path in paths:
        resolved = Path(path).resolve()
        if resolved in seen:
            continue
        seen.add(resolved)
        result.append(Path(path))
    return result


def _local_name(tag: str) -> str:
    return tag.rsplit("}", 1)[-1]


def _display_path(path: Optional[Path]) -> str:
    return str(path) if path else "-"


def _net_prefix(path: Optional[Path]) -> str:
    if not path:
        return ""
    name = Path(path).name
    suffix = ".net.xml"
    if name.lower().endswith(suffix):
        return name[: -len(suffix)]
    return Path(path).stem


def _route_prefix(path: Optional[Path]) -> str:
    if not path:
        return ""
    name = Path(path).name
    for suffix in (".rou.xml", ".routes.xml", ".trips.xml", ".vtypes.xml"):
        if name.lower().endswith(suffix):
            return name[: -len(suffix)]
    return ""


def _route_files_for_prefix(scenario_dir: Path, prefix: str) -> List[Path]:
    if not prefix:
        return []
    ordered: List[Path] = []
    vtypes = scenario_dir / f"{prefix}.vtypes.xml"
    if vtypes.exists():
        ordered.append(vtypes)
    for suffix in (".rou.xml", ".routes.xml", ".trips.xml"):
        candidate = scenario_dir / f"{prefix}{suffix}"
        if candidate.exists():
            ordered.append(candidate)
    main_routes = [path for path in ordered if not path.name.lower().endswith(".vtypes.xml")]
    if not main_routes:
        return []
    return _unique_paths(ordered)


def _route_file_belongs_to_prefix(path: Path, prefix: str) -> bool:
    if not prefix:
        return True
    return Path(path).name.lower().startswith(str(prefix).lower() + ".")


def _select_osm_file(scenario_dir: Path, prefix: str) -> Optional[Path]:
    if prefix:
        preferred = scenario_dir / f"{prefix}.osm"
        if preferred.exists():
            return preferred
    matches = sorted(scenario_dir.glob("*.osm"))
    return matches[0] if matches else None


def _net_tls_ids(net: Optional[Path]) -> Set[str]:
    ids: Set[str] = set()
    if not net:
        return ids
    try:
        for _, elem in ET.iterparse(net, events=("start",)):
            name = _local_name(elem.tag)
            if name == "tlLogic":
                tls_id = elem.attrib.get("id")
                if tls_id:
                    ids.add(tls_id)
            elif name == "junction" and elem.attrib.get("type") == "traffic_light":
                tls_id = elem.attrib.get("id")
                if tls_id:
                    ids.add(tls_id)
    except Exception:
        return ids
    return ids


def _timing_tls_ids(path: Optional[Path]) -> Set[str]:
    ids: Set[str] = set()
    if not path:
        return ids
    try:
        for _, elem in ET.iterparse(path, events=("start",)):
            if _local_name(elem.tag) == "tlLogic":
                tls_id = elem.attrib.get("id")
                if tls_id:
                    ids.add(tls_id)
    except Exception:
        return ids
    return ids


def _prepare_real_timing_file(scenario: ScenarioFiles) -> Optional[Path]:
    timing_file = scenario.real_timing_file
    if not timing_file:
        return None
    net_ids = _net_tls_ids(scenario.net)
    timing_ids = _timing_tls_ids(timing_file)
    if not net_ids or not timing_ids:
        return timing_file

    matching = sorted(timing_ids.intersection(net_ids))
    missing = sorted(timing_ids.difference(net_ids))
    scenario.timing_matching_tls = matching
    scenario.timing_missing_tls = missing
    if missing:
        preview = ", ".join(missing[:10])
        scenario.notes.append(
            f"WARNING: {Path(timing_file).name} references TLS not found in {Path(scenario.net).name}: {preview}"
        )
    if not matching:
        scenario.notes.append(
            f"{Path(timing_file).name} skipped for real_timing baseline because no tlLogic id matches the selected net-file."
        )
        scenario.timing_files = [
            path for path in scenario.timing_files if Path(path).resolve() != Path(timing_file).resolve()
        ]
        return None
    if not missing:
        return timing_file

    filtered = scenario.scenario_dir / AUTOGENERATED_FILTERED_TIMING
    _write_filtered_timing_file(timing_file, filtered, set(matching))
    scenario.timing_filtered_file = filtered
    scenario.timing_files = _unique_paths(
        [path for path in scenario.timing_files if Path(path).resolve() != Path(timing_file).resolve()]
        + [filtered]
    )
    scenario.notes.append(
        f"Created {AUTOGENERATED_FILTERED_TIMING} with matching TLS only for real_timing baseline."
    )
    return filtered


def _write_filtered_timing_file(source: Path, output: Path, allowed_tls: Set[str]) -> None:
    tree = ET.parse(source)
    root = tree.getroot()
    filtered_root = ET.Element("additional")
    for child in list(root):
        if _local_name(child.tag) == "tlLogic" and child.attrib.get("id") in allowed_tls:
            filtered_root.append(copy.deepcopy(child))
    ET.ElementTree(filtered_root).write(output, encoding="utf-8", xml_declaration=True)


def _count_persons(path: Path) -> int:
    count = 0
    try:
        for _, elem in ET.iterparse(path, events=("start",)):
            if _local_name(elem.tag) in {"person", "personFlow"}:
                count += 1
    except Exception:
        return 0
    return count


def _estimate_route_counts(route_files: Sequence[Path]) -> dict:
    counts = {
        "vehicles": 0,
        "trips": 0,
        "flows": 0,
        "persons": 0,
        "person_flows": 0,
        "vtypes": 0,
    }
    for path in route_files:
        try:
            for _, elem in ET.iterparse(path, events=("start",)):
                name = _local_name(elem.tag)
                if name == "vehicle":
                    counts["vehicles"] += 1
                elif name == "trip":
                    counts["trips"] += 1
                elif name == "flow":
                    counts["flows"] += 1
                elif name == "person":
                    counts["persons"] += 1
                elif name == "personFlow":
                    counts["person_flows"] += 1
                elif name in {"vType", "vTypeDistribution"}:
                    counts["vtypes"] += 1
        except Exception:
            continue
    counts["vehicle_count_estimate"] = counts["vehicles"] + counts["trips"] + counts["flows"]
    counts["pedestrian_count_estimate"] = counts["persons"] + counts["person_flows"]
    return counts


def _estimate_net_lane_counts(net: Optional[Path]) -> dict:
    counts = {
        "vehicle_lanes_count": 0,
        "pedestrian_lanes_count": 0,
        "internal_lanes_count": 0,
    }
    if not net:
        return counts
    try:
        for _, elem in ET.iterparse(net, events=("start",)):
            if _local_name(elem.tag) != "lane":
                continue
            lane_id = elem.attrib.get("id", "")
            if lane_id.startswith(":"):
                counts["internal_lanes_count"] += 1
                continue
            allow = set((elem.attrib.get("allow") or "").split())
            disallow = set((elem.attrib.get("disallow") or "").split())
            is_walk = "walkingarea" in lane_id.lower() or "crossing" in lane_id.lower()
            if is_walk or (allow and allow.issubset({"pedestrian"})):
                counts["pedestrian_lanes_count"] += 1
                continue
            if allow and not allow.intersection(VEHICLE_CLASSES):
                continue
            if "all" in disallow and not allow:
                continue
            counts["vehicle_lanes_count"] += 1
    except Exception:
        return counts
    return counts


def build_scenario_summary(scenario: ScenarioFiles, tls_ids: Optional[Sequence[str]] = None) -> dict:
    route_counts = _estimate_route_counts(scenario.route_files)
    lane_counts = _estimate_net_lane_counts(scenario.net)
    route_names = [Path(path).name for path in scenario.route_files]
    return {
        "net_file": Path(scenario.net).name if scenario.net else None,
        "route_files": route_names,
        "tls_count": len(tls_ids or []),
        "tls_ids": list(tls_ids or []),
        "vehicle_lanes_count": lane_counts["vehicle_lanes_count"],
        "pedestrian_lanes_count": lane_counts["pedestrian_lanes_count"],
        "route_vehicle_count_estimate": route_counts["vehicle_count_estimate"],
        "has_vtypes": bool(route_counts["vtypes"] or any(name.endswith(".vtypes.xml") for name in route_names)),
        "has_pedestrians": bool(
            route_counts["pedestrian_count_estimate"]
            or scenario.pedestrian_existing_found
            or scenario.pedestrian_autogenerated
            or scenario.pedestrian_route_file
        ),
        "generated_pedestrians": bool(scenario.pedestrian_autogenerated),
        "osm_file_present": bool(scenario.osm_file and Path(scenario.osm_file).exists()),
    }
