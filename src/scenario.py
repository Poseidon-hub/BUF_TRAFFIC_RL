def _smoke_test_pedestrian_file(scenario_dir: Path, net: Path, pedestrian_file: Path) -> Tuple[bool, str]:
    sumo_cmd = detect_sumo_cmd(use_gui=False)
    if not sumo_cmd:
        return False, "sumo executable not found"
    tmp_sumocfg = Path(scenario_dir) / "_pedestrian_smoke.sumocfg"
