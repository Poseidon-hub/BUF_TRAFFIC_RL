@dataclass
class ScenarioFiles:
    scenario_dir: Path
    sumocfg: Optional[Path] = None
    net: Optional[Path] = None
    route_files: List[Path] = field(default_factory=list)
    additional_files: List[Path] = field(default_factory=list)
    timing_files: List[Path] = field(default_factory=list)
    real_timing_file: Optional[Path] = None
    mode_sumocfgs: dict = field(default_factory=dict)
    autogenerated: bool = False
    found: bool = False
    source: str = "none"
    notes: List[str] = field(default_factory=list)
    pedestrian_existing_found: bool = False
    pedestrian_autogenerated: bool = False
    pedestrian_route_file: Optional[Path] = None
    pedestrian_count: int = 0
    pedestrian_mode: str = "random_walks"
    pedestrian_tls_sensitive_routes: int = 0
    pedestrian_route_warning: str = ""
    pedestrian_metadata: dict = field(default_factory=dict)
    osm_file: Optional[Path] = None
    scenario_prefix: str = ""
    timing_matching_tls: List[str] = field(default_factory=list)
    timing_missing_tls: List[str] = field(default_factory=list)
    timing_filtered_file: Optional[Path] = None

    @property
    def primary_route(self) -> Optional[Path]:
        return self.route_files[0] if self.route_files else None

    @property
    def primary_additional(self) -> Optional[Path]:
        return self.additional_files[0] if self.additional_files else None

    def as_legacy_dict(self) -> dict:
        return {
            "sumocfg": self.sumocfg,
            "net": self.net,
            "rou": self.primary_route,
            "add": self.primary_additional,
            "route_files": list(self.route_files),
            "additional_files": list(self.additional_files),
            "timing_files": list(self.timing_files),
            "real_timing_file": self.real_timing_file,
            "found": self.found,
        }

    def sumocfg_for_mode(self, mode: str) -> Optional[Path]:
        normalized = normalize_sumo_mode(mode)
        return self.mode_sumocfgs.get(normalized) or self.sumocfg


def normalize_sumo_mode(mode: str) -> str:
    if mode == "fixed":
        return "fixed_native"
    return str(mode or "fixed_native")


def discover_scenario(
    scenario_dir: Path,
    begin: float = 0.0,
    end: float = 300.0,
    step_length: float = 1.0,
    auto_generate_sumocfg: bool = True,
    scenario_sumocfg_file: Optional[Path] = None,
    scenario_net_file: Optional[Path] = None,
    scenario_route_file: Optional[Path] = None,
    auto_generate_pedestrians_if_missing: bool = False,
    pedestrian_count: int = 30,
    pedestrian_begin: int = 0,
    pedestrian_end: int = 300,
    pedestrian_prefix: str = "auto_ped",
    pedestrian_mode: str = "random_walks",
    real_timing_file_name: str = "tls.add.xml",
    rl_use_real_timing_program_as_base: bool = True,
    scenario_preferred_prefix: str = "kaliningrad",
    allow_mixed_scenario_files: bool = False,
    preferred_controlled_tls_ids: Optional[Sequence[str]] = None,
) -> ScenarioFiles:
    scenario_dir = Path(scenario_dir)
    scenario_dir.mkdir(parents=True, exist_ok=True)

    explicit_sumocfg = _resolve_optional_path(scenario_dir, scenario_sumocfg_file)
    if explicit_sumocfg and explicit_sumocfg.exists():
        scenario = _scenario_from_sumocfg(scenario_dir, explicit_sumocfg, source="explicit_sumocfg")
        return _finalize_scenario(
            scenario,
            begin,
            end,
            step_length,
            auto_generate_sumocfg,
            auto_generate_pedestrians_if_missing,
            pedestrian_count,
            pedestrian_begin,
            pedestrian_end,
            pedestrian_prefix,
            pedestrian_mode,
            real_timing_file_name,
            rl_use_real_timing_program_as_base,
            preferred_controlled_tls_ids,
        )

    net = _select_net_file(scenario_dir, scenario_net_file, scenario_preferred_prefix)
    explicit_route = _resolve_optional_path(scenario_dir, scenario_route_file)
    explicit_route_selected = bool(explicit_route and explicit_route.exists())
    route_files = [
        path
        for path in _select_route_files(
            scenario_dir,
            scenario_route_file,
            selected_net=net,
            preferred_prefix=scenario_preferred_prefix,
            allow_mixed_scenario_files=allow_mixed_scenario_files,
        )
        if path.name != AUTOGENERATED_PEDESTRIANS
    ]
    if not net or not route_files:
        user_sumocfgs = [
            path
            for path in sorted(scenario_dir.glob("*.sumocfg"))
            if path.name.lower()
            not in {
                AUTOGENERATED_SUMOCFG,
                AUTOGENERATED_NATIVE_SUMOCFG,
                AUTOGENERATED_REAL_TIMING_SUMOCFG,
                AUTOGENERATED_RL_SUMOCFG,
            }
        ]
        if user_sumocfgs:
            scenario = _scenario_from_sumocfg(scenario_dir, user_sumocfgs[0], source="sumocfg")
            return _finalize_scenario(
                scenario,
                begin,
                end,
                step_length,
                auto_generate_sumocfg,
                auto_generate_pedestrians_if_missing,
                pedestrian_count,
                pedestrian_begin,
                pedestrian_end,
                pedestrian_prefix,
                pedestrian_mode,
                real_timing_file_name,
                rl_use_real_timing_program_as_base,
                preferred_controlled_tls_ids,
            )
        generated = scenario_dir / AUTOGENERATED_SUMOCFG
        if generated.exists():
            parsed = _scenario_from_sumocfg(scenario_dir, generated, source="autogenerated_sumocfg")
            if parsed.net and parsed.route_files:
                return _finalize_scenario(
                    parsed,
                    begin,
                    end,
                    step_length,
                    auto_generate_sumocfg,
                    auto_generate_pedestrians_if_missing,
                    pedestrian_count,
                    pedestrian_begin,
                    pedestrian_end,
                    pedestrian_prefix,
                    pedestrian_mode,
                    real_timing_file_name,
                    rl_use_real_timing_program_as_base,
                    preferred_controlled_tls_ids,
                )
        return ScenarioFiles(scenario_dir=scenario_dir, found=False)

    scenario_prefix = _net_prefix(net)
    strict_prefix_routes = (
        bool(scenario_prefix)
        and bool(scenario_preferred_prefix)
        and scenario_prefix.lower() == str(scenario_preferred_prefix).lower()
        and not bool(allow_mixed_scenario_files)
    )
    route_files, additional_files, timing_files, notes = _classify_companion_xml(
        scenario_dir,
        net,
        route_files,
        scenario_prefix=scenario_prefix if strict_prefix_routes else "",
        allow_mixed_scenario_files=allow_mixed_scenario_files,
        include_companion_routes=not explicit_route_selected,
    )
    scenario = ScenarioFiles(
        scenario_dir=scenario_dir,
        net=net,
        route_files=route_files,
        additional_files=additional_files,
        timing_files=timing_files,
        found=True,
        source="net_and_routes",
        notes=notes,
        scenario_prefix=scenario_prefix,
        osm_file=_select_osm_file(scenario_dir, scenario_prefix),
    )
    return _finalize_scenario(
        scenario,
        begin,
        end,
        step_length,
        auto_generate_sumocfg,
        auto_generate_pedestrians_if_missing,
        pedestrian_count,
        pedestrian_begin,
        pedestrian_end,
        pedestrian_prefix,
        pedestrian_mode,
        real_timing_file_name,
        rl_use_real_timing_program_as_base,
        preferred_controlled_tls_ids,
    )


def _finalize_scenario(
    scenario: ScenarioFiles,
    begin: float,
    end: float,
    step_length: float,
    auto_generate_sumocfg: bool,
    auto_generate_pedestrians_if_missing: bool,
    pedestrian_count: int,
    pedestrian_begin: int,
    pedestrian_end: int,
    pedestrian_prefix: str,
    pedestrian_mode: str,
    real_timing_file_name: str,
    rl_use_real_timing_program_as_base: bool,
    preferred_controlled_tls_ids: Optional[Sequence[str]] = None,
) -> ScenarioFiles:
    if not scenario.found:
        return scenario
    scenario.pedestrian_mode = str(pedestrian_mode or "random_walks").strip().lower()
    preferred_tls_ids = _normalize_tls_ids(preferred_controlled_tls_ids)

    if scenario.net and not scenario.scenario_prefix:
        scenario.scenario_prefix = _net_prefix(scenario.net)
    if scenario.osm_file is None:
        scenario.osm_file = _select_osm_file(scenario.scenario_dir, scenario.scenario_prefix)

    ordinary, timing = _split_timing_files(scenario.additional_files)
    scenario.additional_files = ordinary
    scenario.timing_files = _unique_paths([*scenario.timing_files, *timing])
    named_timing = scenario.scenario_dir / str(real_timing_file_name)
    if named_timing.exists() and named_timing not in scenario.timing_files:
        kind, _ = _classify_xml(named_timing)
        if kind == "timing":
            scenario.timing_files.append(named_timing)
    scenario.timing_files = _unique_paths(scenario.timing_files)
    scenario.real_timing_file = _select_real_timing_file(scenario.timing_files, real_timing_file_name)
    scenario.real_timing_file = _prepare_real_timing_file(scenario)

    scenario.route_files = [path for path in scenario.route_files if path.name != AUTOGENERATED_PEDESTRIANS]
    scenario.pedestrian_existing_found = route_files_have_pedestrians(scenario.route_files)
    generated_pedestrians = scenario.scenario_dir / AUTOGENERATED_PEDESTRIANS
    if (
        generated_pedestrians.exists()
        and preferred_tls_ids
        and auto_generate_pedestrians_if_missing
        and scenario.pedestrian_mode == "crossing_focused"
    ):
        metadata = _load_autogenerated_pedestrian_metadata(scenario.scenario_dir)
        if not _pedestrian_metadata_matches_preferred_tls(metadata, preferred_tls_ids):
            scenario.notes.append(
                "Existing autogenerated_pedestrians.rou.xml does not target the selected controlled TLS; regenerating."
            )
            try:
                generated_pedestrians.unlink(missing_ok=True)
                (scenario.scenario_dir / AUTOGENERATED_PEDESTRIANS_META).unlink(missing_ok=True)
            except Exception:
                pass
    if (
        scenario.net
        and not scenario.pedestrian_existing_found
        and generated_pedestrians.exists()
    ):
        if _skip_pedestrian_route_smoke_test():
            ok, message = True, "pedestrian route smoke-test skipped"
        else:
            ok, message = _smoke_test_pedestrian_file(scenario.scenario_dir, scenario.net, generated_pedestrians)
        if ok:
            scenario.route_files.append(generated_pedestrians)
            scenario.pedestrian_route_file = generated_pedestrians
            scenario.pedestrian_count = _count_persons(generated_pedestrians)
            scenario.pedestrian_metadata = _load_autogenerated_pedestrian_metadata(scenario.scenario_dir)
            scenario.pedestrian_tls_sensitive_routes = int(
                scenario.pedestrian_metadata.get("tls_sensitive_routes", 0) or 0
            )
            scenario.pedestrian_route_warning = str(
                scenario.pedestrian_metadata.get("warning", "") or ""
            )
            scenario.notes.append("Using existing autogenerated_pedestrians.rou.xml.")
        else:
            scenario.notes.append(
                "Existing autogenerated_pedestrians.rou.xml is incompatible with the selected net-file "
                f"and will be regenerated if enabled: {message}"
            )
            try:
                generated_pedestrians.unlink(missing_ok=True)
            except Exception:
                pass

    if (
        scenario.net
        and not scenario.pedestrian_existing_found
        and scenario.pedestrian_route_file is None
        and auto_generate_pedestrians_if_missing
    ):
        ok, message, generated = generate_pedestrian_demand(
            scenario_dir=scenario.scenario_dir,
            net=scenario.net,
            count=pedestrian_count,
            begin=pedestrian_begin,
            end=pedestrian_end,
            prefix=pedestrian_prefix,
            pedestrian_mode=scenario.pedestrian_mode,
            preferred_controlled_tls_ids=preferred_tls_ids,
        )
        if ok and generated:
            scenario.route_files.append(generated)
            scenario.pedestrian_autogenerated = True
            scenario.pedestrian_route_file = generated
            scenario.pedestrian_count = _count_persons(generated)
            scenario.pedestrian_metadata = _load_autogenerated_pedestrian_metadata(scenario.scenario_dir)
            scenario.pedestrian_tls_sensitive_routes = int(
                scenario.pedestrian_metadata.get("tls_sensitive_routes", 0) or 0
            )
            scenario.pedestrian_route_warning = str(
                scenario.pedestrian_metadata.get("warning", "") or ""
            )
            scenario.notes.append("Пешеходы не найдены. Создан autogenerated_pedestrians.rou.xml для dev-проверки.")
            if scenario.pedestrian_route_warning:
                scenario.notes.append(scenario.pedestrian_route_warning)
        else:
            scenario.notes.append(message)
    if auto_generate_sumocfg:
        scenario.autogenerated = True
        write_mode_sumocfgs(
            scenario,
            begin=begin,
            end=end,
            step_length=step_length,
            rl_use_real_timing_program_as_base=rl_use_real_timing_program_as_base,
        )
    return scenario


def route_files_have_pedestrians(route_files: Sequence[Path]) -> bool:
    for path in route_files:
        try:
            _, tags = _classify_xml(Path(path))
            if PERSON_TAGS.intersection(tags):
                return True
        except Exception:
            continue
    return False


def generate_pedestrian_demand(
    scenario_dir: Path,
    net: Path,
    count: int,
    begin: int,
    end: int,
    prefix: str,
    pedestrian_mode: str = "random_walks",
    preferred_controlled_tls_ids: Optional[Sequence[str]] = None,
) -> Tuple[bool, str, Optional[Path]]:
    scenario_dir = Path(scenario_dir)
    output = scenario_dir / AUTOGENERATED_PEDESTRIANS
    meta_path = scenario_dir / AUTOGENERATED_PEDESTRIANS_META
    mode = str(pedestrian_mode or "random_walks").strip().lower()
    preferred_tls_ids = _normalize_tls_ids(preferred_controlled_tls_ids)
    if mode == "existing_persons":
        _write_pedestrian_metadata(
            meta_path,
            {
                "pedestrian_mode": mode,
                "requested_count": int(count),
                "actual_persons": 0,
                "tls_sensitive_routes": 0,
                "warning": "Pedestrian mode existing_persons requested, but no existing persons were found.",
            },
        )
        return False, "Pedestrian mode existing_persons requested, but no existing persons were found.", None
    try:
        add_sumo_tools_to_path()
        import sumolib

        sumo_net = sumolib.net.readNet(str(net), withInternal=True)
        edges = []
        edge_nodes = {}
        for edge in sumo_net.getEdges():
            edge_id = edge.getID()
            if edge_id.startswith(":"):
                continue
            try:
                if edge.allows("pedestrian"):
                    edges.append(edge_id)
                    edge_nodes[edge_id] = _edge_node_pair(edge)
                    continue
            except Exception:
                pass
            try:
                if any(lane.allows("pedestrian") for lane in edge.getLanes()):
                    edges.append(edge_id)
                    edge_nodes[edge_id] = _edge_node_pair(edge)
            except Exception:
                continue
    except Exception as exc:
        return False, f"Could not generate pedestrian routes: {exc}", None

    if not edges:
        return False, "Could not generate pedestrian routes: no pedestrian-compatible edges found.", None

    edges = sorted(dict.fromkeys(edges))
    demand_count = max(0, int(count))
    begin = int(begin)
    end = max(begin + 1, int(end))

    warning = ""
    pairs = []
    tls_sensitive_edges: list[str] = []
    controlled_tls_edges: list[str] = []
    controlled_tls_sensitive_count = 0
    pair_source = "all_pedestrian_edges"
    tls_diagnostics: dict = {
        "preferred_controlled_tls_ids": preferred_tls_ids,
        "controlled_tls_ids": [],
        "controlled_tls_overlap_count": 0,
        "controlled_tls_overlap_edges": [],
        "controlled_tls_edges_by_tls": {},
    }
    if mode == "crossing_focused":
        if preferred_tls_ids:
            (
                pairs,
                controlled_tls_edges,
                tls_diagnostics,
                warning,
            ) = _controlled_tls_pedestrian_pairs(
                net=Path(net),
                pedestrian_edges=edges,
                edge_nodes=edge_nodes,
                preferred_tls_ids=preferred_tls_ids,
            )
            if pairs:
                tls_sensitive_edges = list(controlled_tls_edges)
                controlled_tls_sensitive_count = demand_count
                pair_source = "preferred_controlled_tls"
                if int(tls_diagnostics.get("pedestrian_signal_link_count", 0) or 0) <= 0:
                    warning = (
                        "Selected controlled TLS do not expose pedestrian signal links in net.xml; "
                        "pedestrian timing metrics may match fixed-time even when vehicle phases change."
                    )
        if not pairs:
            fallback_warning = ""
            pairs, tls_sensitive_edges, fallback_warning = _tls_sensitive_pedestrian_pairs(
                net=Path(net),
                pedestrian_edges=edges,
                edge_nodes=edge_nodes,
            )
            pair_source = "global_tls"
            if preferred_tls_ids:
                warning = (
                    warning
                    or fallback_warning
                    or "Could not generate pedestrian routes on selected controlled TLS; using global TLS-sensitive routes."
                )
                tls_diagnostics["fallback_to_global_tls"] = True
            else:
                warning = fallback_warning
        if not pairs:
            warning = warning or "Could not generate TLS-sensitive pedestrian routes; pedestrian metrics may be identical."
    if not pairs:
        shift = max(1, len(edges) // 2)
        pairs = [(edges[idx % len(edges)], edges[(idx + shift) % len(edges)]) for idx in range(max(1, len(edges)))]
        pair_source = "all_pedestrian_edges"

    person_ids = [f"{prefix}_{idx}" for idx in range(demand_count)]
    _write_pedestrian_routes(output, pairs, demand_count, begin, end, prefix)
    tls_sensitive_count = demand_count if mode == "crossing_focused" and tls_sensitive_edges else 0
    controlled_tls_sensitive_person_ids = person_ids if controlled_tls_sensitive_count else []
    _write_pedestrian_metadata(
        meta_path,
        {
            "pedestrian_mode": mode,
            "requested_count": int(count),
            "actual_persons": demand_count,
            "depart_window": f"{begin}..{end}",
            "tls_sensitive_routes": tls_sensitive_count,
            "controlled_tls_sensitive_routes": controlled_tls_sensitive_count,
            "warning": warning,
            "route_file": output.name,
            "person_ids": person_ids,
            "tls_sensitive_person_ids": person_ids if tls_sensitive_count else [],
            "controlled_tls_sensitive_person_ids": controlled_tls_sensitive_person_ids,
            "tls_sensitive_edges": list(tls_sensitive_edges)[:200],
            "controlled_tls_overlap_edges": list(controlled_tls_edges)[:200],
            "controlled_tls_overlap_count": len(controlled_tls_edges),
            "preferred_controlled_tls_ids": preferred_tls_ids,
            "controlled_tls_ids": list(tls_diagnostics.get("controlled_tls_ids", [])),
            "controlled_tls_edges_by_tls": {
                str(tls_id): list(values)[:50]
                for tls_id, values in (tls_diagnostics.get("controlled_tls_edges_by_tls", {}) or {}).items()
            },
            "controlled_lane_overlap_edges": list(tls_diagnostics.get("controlled_lane_overlap_edges", []) or [])[:200],
            "controlled_tls_junctions": list(tls_diagnostics.get("controlled_tls_junctions", []) or [])[:200],
            "pedestrian_signal_link_count": int(tls_diagnostics.get("pedestrian_signal_link_count", 0) or 0),
            "pedestrian_signal_links_by_tls": {
                str(tls_id): int(count)
                for tls_id, count in (tls_diagnostics.get("pedestrian_signal_links_by_tls", {}) or {}).items()
            },
            "pedestrian_pair_source": pair_source,
            "walk_pairs_sample": [
                {"from": str(from_edge), "to": str(to_edge)}
                for from_edge, to_edge in list(pairs)[:20]
            ],
            "pedestrian_edges_sample": list(edges)[:20],
        },
    )
    if _skip_pedestrian_route_smoke_test():
        return True, "", output
    ok, message = _smoke_test_pedestrian_file(scenario_dir, net, output)
    if ok:
        return True, "", output

    # Fallback: same-edge walks are accepted by SUMO on networks where cross-edge
    # pedestrian routing is not available.
    fallback_warning = (
        "Could not generate TLS-sensitive pedestrian routes; pedestrian metrics may be identical. "
        f"Original pedestrian route smoke-test failed: {message}"
    )
    fallback_pairs = [(edge, edge) for edge in edges]
    _write_pedestrian_routes(output, fallback_pairs, demand_count, begin, end, prefix)
    _write_pedestrian_metadata(
        meta_path,
        {
            "pedestrian_mode": mode,
            "requested_count": int(count),
            "actual_persons": demand_count,
            "depart_window": f"{begin}..{end}",
            "tls_sensitive_routes": 0,
            "controlled_tls_sensitive_routes": 0,
            "warning": fallback_warning,
            "route_file": output.name,
            "person_ids": person_ids,
            "tls_sensitive_person_ids": [],
            "controlled_tls_sensitive_person_ids": [],
            "tls_sensitive_edges": [],
            "controlled_tls_overlap_edges": [],
            "controlled_tls_overlap_count": 0,
            "preferred_controlled_tls_ids": preferred_tls_ids,
            "controlled_tls_ids": [],
            "controlled_tls_edges_by_tls": {},
            "controlled_lane_overlap_edges": [],
            "controlled_tls_junctions": [],
            "pedestrian_signal_link_count": 0,
            "pedestrian_signal_links_by_tls": {},
            "pedestrian_pair_source": "same_edge_fallback",
            "pedestrian_edges_sample": list(edges)[:20],
        },
    )
    ok, fallback_message = _smoke_test_pedestrian_file(scenario_dir, net, output)
    if ok:
        return True, "", output
    return False, f"Could not generate pedestrian routes: {message}; fallback failed: {fallback_message}", None


def _write_pedestrian_routes(
    output: Path,
    pairs: Sequence[tuple[str, str]],
    demand_count: int,
    begin: int,
    end: int,
    prefix: str,
) -> None:
    lines = ['<?xml version="1.0" encoding="UTF-8"?>', "<routes>"]
    for idx in range(max(0, int(demand_count))):
        depart = begin + int((end - begin) * idx / max(1, demand_count))
        from_edge, to_edge = pairs[idx % len(pairs)]
        lines.append(f'    <person id="{prefix}_{idx}" depart="{depart}">')
        lines.append(f'        <walk from="{escape(str(from_edge))}" to="{escape(str(to_edge))}"/>')
        lines.append("    </person>")
    lines.append("</routes>")
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _edge_node_pair(edge) -> tuple[str, str]:
    try:
        from_node = edge.getFromNode().getID()
    except Exception:
        from_node = ""
    try:
        to_node = edge.getToNode().getID()
    except Exception:
        to_node = ""
    return str(from_node), str(to_node)


def _normalize_tls_ids(tls_ids: Optional[Sequence[str]]) -> list[str]:
    result = []
    for tls_id in tls_ids or []:
        text = str(tls_id).strip()
        if text and text not in result:
            result.append(text)
    return result


def _pedestrian_metadata_matches_preferred_tls(metadata: dict, preferred_tls_ids: Sequence[str]) -> bool:
    preferred = set(_normalize_tls_ids(preferred_tls_ids))
    if not preferred:
        return True
    configured = set(_normalize_tls_ids(metadata.get("controlled_tls_ids") or []))
    overlap_count = int(metadata.get("controlled_tls_overlap_count", 0) or 0)
    sensitive_routes = int(metadata.get("controlled_tls_sensitive_routes", 0) or 0)
    return bool(configured.intersection(preferred) and overlap_count > 0 and sensitive_routes > 0)


def _controlled_tls_pedestrian_pairs(
    net: Path,
    pedestrian_edges: Sequence[str],
    edge_nodes: dict,
    preferred_tls_ids: Sequence[str],
) -> tuple[list[tuple[str, str]], list[str], dict, str]:
    preferred = _normalize_tls_ids(preferred_tls_ids)
    diagnostics = {
        "preferred_controlled_tls_ids": preferred,
        "controlled_tls_ids": [],
        "controlled_tls_overlap_count": 0,
        "controlled_tls_overlap_edges": [],
        "controlled_tls_edges_by_tls": {},
        "controlled_lane_overlap_edges": [],
        "controlled_tls_junctions": [],
        "pedestrian_signal_link_count": 0,
        "pedestrian_signal_links_by_tls": {},
    }
    if not preferred:
        return [], [], diagnostics, ""

    try:
        add_sumo_tools_to_path()
        import sumolib

        sumo_net = sumolib.net.readNet(str(net), withPrograms=True, withConnections=True, withInternal=True)
    except Exception as exc:
        return [], [], diagnostics, f"Could not inspect selected controlled TLS for pedestrians: {exc}"

    pedestrian_edge_set = set(str(edge_id) for edge_id in pedestrian_edges)
    tls_by_id = {str(tls.getID()): tls for tls in sumo_net.getTrafficLights()}
    traffic_light_junctions = _tls_junction_ids(net)
    selected_junctions_by_tls: dict[str, list[str]] = {}
    pedestrian_signal_links_by_tls: dict[str, int] = {}
    lane_overlap_edges: set[str] = set()
    missing_tls = []

    for tls_id in preferred:
        tls = tls_by_id.get(tls_id)
        if tls is None:
            missing_tls.append(tls_id)
            continue
        controlled_edges = set()
        selected_junctions = set()
        for conn in tls.getConnections():
            lanes = _connection_lanes(conn)
            if _connection_has_pedestrian_signal_lane(conn):
                pedestrian_signal_links_by_tls[tls_id] = pedestrian_signal_links_by_tls.get(tls_id, 0) + 1
            for lane in lanes:
                edge_id = _lane_edge_id(lane)
                if edge_id and not edge_id.startswith(":"):
                    controlled_edges.add(edge_id)
            selected_junctions.update(_connection_junction_ids(conn, traffic_light_junctions))
        lane_overlap_edges.update(edge_id for edge_id in controlled_edges if edge_id in pedestrian_edge_set)
        if selected_junctions:
            selected_junctions_by_tls[tls_id] = sorted(selected_junctions)

    junction_to_tls: dict[str, str] = {}
    for tls_id, junctions in selected_junctions_by_tls.items():
        for junction_id in junctions:
            junction_to_tls.setdefault(junction_id, tls_id)

    by_junction: dict[str, list[str]] = {junction: [] for junction in junction_to_tls}
    for edge_id in pedestrian_edges:
        from_node, to_node = edge_nodes.get(edge_id, ("", ""))
        for node_id in (from_node, to_node):
            if node_id in by_junction:
                by_junction[node_id].append(edge_id)

    pairs: list[tuple[str, str]] = []
    sensitive_edges: set[str] = set()
    edges_by_tls: dict[str, list[str]] = {}
    for junction_id in sorted(by_junction):
        node_edges = sorted(dict.fromkeys(by_junction[junction_id]))
        if len(node_edges) < 2:
            continue
        tls_id = junction_to_tls.get(junction_id, "")
        if tls_id:
            current = edges_by_tls.setdefault(tls_id, [])
            for edge_id in node_edges:
                if edge_id not in current:
                    current.append(edge_id)
        half = max(1, len(node_edges) // 2)
        for idx, from_edge in enumerate(node_edges):
            to_edge = node_edges[(idx + half) % len(node_edges)]
            if from_edge == to_edge:
                continue
            pairs.append((from_edge, to_edge))
            sensitive_edges.add(from_edge)
            sensitive_edges.add(to_edge)

    if not pairs and lane_overlap_edges:
        lane_edges = sorted(lane_overlap_edges)
        for tls_id in preferred:
            tls_edges = [edge_id for edge_id in lane_edges if edge_id in lane_overlap_edges]
            if len(tls_edges) < 2:
                continue
            half = max(1, len(tls_edges) // 2)
            for idx, from_edge in enumerate(tls_edges):
                to_edge = tls_edges[(idx + half) % len(tls_edges)]
                if from_edge == to_edge:
                    continue
                pairs.append((from_edge, to_edge))
                sensitive_edges.add(from_edge)
                sensitive_edges.add(to_edge)
            if pairs:
                edges_by_tls[tls_id] = tls_edges
                break

    diagnostics.update(
        {
            "controlled_tls_ids": list(edges_by_tls.keys()),
            "controlled_tls_overlap_count": len(sensitive_edges),
            "controlled_tls_overlap_edges": sorted(sensitive_edges)[:200],
            "controlled_tls_edges_by_tls": edges_by_tls,
            "controlled_lane_overlap_edges": sorted(lane_overlap_edges)[:200],
            "controlled_tls_junctions": sorted(junction_to_tls.keys())[:200],
            "pedestrian_signal_link_count": sum(pedestrian_signal_links_by_tls.values()),
            "pedestrian_signal_links_by_tls": pedestrian_signal_links_by_tls,
            "missing_tls_ids": missing_tls,
        }
    )
    if not pairs:
        return (
            [],
            [],
            diagnostics,
            "Could not generate pedestrian routes on selected controlled TLS; pedestrian metrics may be identical.",
        )
    return pairs, sorted(sensitive_edges), diagnostics, ""


def _connection_lanes(conn) -> list:
    lanes = []
    try:
        if isinstance(conn, (list, tuple)):
            lanes.extend([item for item in conn[:2] if item is not None])
            return lanes
    except Exception:
        pass
    for method_name in ("getFromLane", "getToLane"):
        try:
            lane = getattr(conn, method_name)()
            if lane is not None:
                lanes.append(lane)
        except Exception:
            continue
    return lanes


def _connection_junction_ids(conn, traffic_light_junctions: set[str]) -> set[str]:
    junctions = set()
    lanes = _connection_lanes(conn)
    for index, lane in enumerate(lanes[:2]):
        try:
            edge = lane.getEdge()
        except Exception:
            continue
        node_candidates = []
        try:
            if index == 0:
                node_candidates.append(edge.getToNode().getID())
            else:
                node_candidates.append(edge.getFromNode().getID())
        except Exception:
            pass
        try:
            node_candidates.extend([edge.getFromNode().getID(), edge.getToNode().getID()])
        except Exception:
            pass
        for node_id in node_candidates:
            node_text = str(node_id)
            if not traffic_light_junctions or node_text in traffic_light_junctions:
                junctions.add(node_text)
    return junctions


def _connection_has_pedestrian_signal_lane(conn) -> bool:
    return any(_lane_is_pedestrian_signal_lane(lane) for lane in _connection_lanes(conn))


def _lane_is_pedestrian_signal_lane(lane) -> bool:
    lane_id = ""
    edge_id = ""
    try:
        lane_id = str(lane.getID())
    except Exception:
        lane_id = ""
    try:
        edge_id = str(lane.getEdge().getID())
    except Exception:
        edge_id = ""
    lowered = f"{lane_id} {edge_id}".lower()
    if "crossing" in lowered or "walkingarea" in lowered:
        return True
    try:
        pedestrian = bool(lane.allows("pedestrian"))
    except Exception:
        pedestrian = False
    if not pedestrian:
        return False
    for vehicle_class in ("passenger", "private", "bus", "truck", "taxi", "delivery"):
        try:
            if lane.allows(vehicle_class):
                return False
        except Exception:
            continue
    return True


def _lane_edge_id(lane) -> str:
    try:
        edge = lane.getEdge()
        return str(edge.getID())
    except Exception:
        return ""


def _tls_sensitive_pedestrian_pairs(
    net: Path,
    pedestrian_edges: Sequence[str],
    edge_nodes: dict,
) -> tuple[list[tuple[str, str]], list[str], str]:
    tls_junctions = _tls_junction_ids(net)
    if not tls_junctions:
        return [], [], "Could not generate TLS-sensitive pedestrian routes: no traffic_light junctions found."

    by_junction: dict[str, list[str]] = {junction: [] for junction in tls_junctions}
    for edge_id in pedestrian_edges:
        from_node, to_node = edge_nodes.get(edge_id, ("", ""))
        for node_id in (from_node, to_node):
            if node_id in by_junction:
                by_junction[node_id].append(edge_id)

    pairs: list[tuple[str, str]] = []
    sensitive_edges: set[str] = set()
    for junction_id in sorted(by_junction):
        node_edges = sorted(dict.fromkeys(by_junction[junction_id]))
        if len(node_edges) < 2:
            continue
        half = max(1, len(node_edges) // 2)
        for idx, from_edge in enumerate(node_edges):
            to_edge = node_edges[(idx + half) % len(node_edges)]
            if to_edge == from_edge:
                continue
            pairs.append((from_edge, to_edge))
            sensitive_edges.add(from_edge)
            sensitive_edges.add(to_edge)
    if not pairs:
        return [], [], "Could not generate TLS-sensitive pedestrian routes; pedestrian metrics may be identical."
    return pairs, sorted(sensitive_edges), ""


def _tls_junction_ids(net: Path) -> set[str]:
    try:
        root = ET.parse(net).getroot()
    except Exception:
        return set()
    result = set()
    for junction in root.findall("junction"):
        junction_type = str(junction.get("type", "")).lower()
        if "traffic_light" in junction_type:
            junction_id = junction.get("id")
            if junction_id:
                result.add(str(junction_id))
    return result


